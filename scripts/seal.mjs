#!/usr/bin/env node
/**
 * Generates an embedded build seal from dist/index.html's inline application
 * code and styles. The seal script itself is marked and excluded from the hash,
 * and application <style> tags are marked with `data-snakebyte-style` so
 * browser extensions (e.g. Dark Reader, Stylus) do not trigger false resets.
 *
 * By default this seals `dist/index.html` and `dist/integrity.js` without
 * dirtying tracked git files. Pass `--write-source` to also update `index.html`
 * and `public/integrity.js`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fingerprintHtml, injectSeal, markAppStyles } from "./seal-lib.mjs";

const BUILT_HTML = "dist/index.html";
const SOURCE_HTML = "index.html";
const PUBLIC_MIRROR = "public/integrity.js";
const BUILT_MIRROR = "dist/integrity.js";
const writeSource = process.argv.includes("--write-source");

if (!existsSync(BUILT_HTML))
  throw new Error(`Missing ${BUILT_HTML}. Run \`npm run build\` first.`);

const rawBuilt = readFileSync(BUILT_HTML, "utf8");
const markedBuilt = markAppStyles(rawBuilt);
const { hash, scripts, styles } = fingerprintHtml(markedBuilt);
const sealText = `/* Generated by scripts/seal.mjs — do not hand-edit. */\nwindow.__SNAKEBYTE_SEAL__ = Object.freeze({ v: 1, fingerprint: "${hash}" });\n`;

writeFileSync(BUILT_HTML, injectSeal(markedBuilt, hash, { markStyles: true }));
if (existsSync("dist")) writeFileSync(BUILT_MIRROR, sealText);

if (writeSource) {
  if (existsSync(SOURCE_HTML)) {
    const source = readFileSync(SOURCE_HTML, "utf8");
    writeFileSync(SOURCE_HTML, injectSeal(source, hash, { markStyles: false }));
  }
  writeFileSync(PUBLIC_MIRROR, sealText);
}

console.log(
  `Embedded seal for ${scripts} inline script(s) and ${styles} stylesheet(s): ${hash}`,
);
