#!/usr/bin/env node
/**
 * Generates an embedded build seal from dist/index.html's inline application
 * code and styles, and replaces `script-src 'self' 'unsafe-inline'` in
 * `dist/_headers` with exact `'sha256-...'` CSP script hashes.
 *
 * By default this seals `dist/index.html`, `dist/_headers`, and
 * `dist/integrity.js` without dirtying tracked git files. Pass `--write-source`
 * to also update `index.html` and `public/integrity.js`, or `--strict-csp` to
 * also rewrite `dist/index.html`'s `<meta>` CSP tag with script hashes.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  applyCspScriptHashes,
  computeCspScriptHashes,
  fingerprintHtml,
  injectSeal,
  markAppStyles,
} from "./seal-lib.mjs";

const BUILT_HTML = "dist/index.html";
const BUILT_HEADERS = "dist/_headers";
const SOURCE_HTML = "index.html";
const PUBLIC_MIRROR = "public/integrity.js";
const BUILT_MIRROR = "dist/integrity.js";
const writeSource = process.argv.includes("--write-source");
const strictMetaCsp = process.argv.includes("--strict-csp");

if (!existsSync(BUILT_HTML))
  throw new Error(`Missing ${BUILT_HTML}. Run \`npm run build\` first.`);

const rawBuilt = readFileSync(BUILT_HTML, "utf8");
const markedBuilt = markAppStyles(rawBuilt);
const { hash, scripts, styles } = fingerprintHtml(markedBuilt);

let sealedHtml = injectSeal(markedBuilt, hash, { markStyles: true });
const scriptHashes = computeCspScriptHashes(sealedHtml);
if (strictMetaCsp) {
  sealedHtml = applyCspScriptHashes(sealedHtml, scriptHashes);
}
writeFileSync(BUILT_HTML, sealedHtml);

if (existsSync(BUILT_HEADERS)) {
  const rawHeaders = readFileSync(BUILT_HEADERS, "utf8");
  writeFileSync(BUILT_HEADERS, applyCspScriptHashes(rawHeaders, scriptHashes));
}

const sealText = `/* Generated by scripts/seal.mjs — do not hand-edit. */\nwindow.__SNAKEBYTE_SEAL__ = Object.freeze({ v: 1, fingerprint: "${hash}", scriptHashes: ${JSON.stringify(scriptHashes)} });\n`;
if (existsSync("dist")) writeFileSync(BUILT_MIRROR, sealText);

if (writeSource) {
  if (existsSync(SOURCE_HTML)) {
    const source = readFileSync(SOURCE_HTML, "utf8");
    writeFileSync(SOURCE_HTML, injectSeal(source, hash, { markStyles: false }));
  }
  writeFileSync(PUBLIC_MIRROR, sealText);
}

console.log(
  `Embedded seal for ${scripts} inline script(s) and ${styles} stylesheet(s): ${hash} (${scriptHashes.length} CSP script hashes)`,
);
